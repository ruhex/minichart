#!/usr/bin/env node
/**
 * Build the distributable bundles.
 *
 *   npm run build          write dist/ and print sizes
 *   npm run build:check    rebuild in memory and fail if dist/ is stale
 *
 * Two artefacts, because one file cannot serve every consumer:
 *
 *   dist/minichart.min.js       minified script/CommonJS build. Publishes
 *                               window.MiniChart, so it works from a <script>
 *                               tag and from a CDN. This is the `unpkg` entry.
 *   dist/minichart.mjs          real ES module ending in `export default`.
 *                               Bundlers (Vite, webpack, Rollup) resolve here.
 *                               Shipped unminified on purpose: every bundler
 *                               minifies it itself, and readable source is what
 *                               tree-shaking and sourcemaps need. There is no
 *                               minified .mjs — nothing consumes one.
 *
 * The .mjs extension is deliberate: this package is not `"type": "module"`, so
 * Node would treat a dist/*.js file as CommonJS and only reach ESM through a
 * warned-about fallback. `.mjs` is unambiguous to every loader.
 *
 * The ESM builds are generated rather than hand-written: `export` is static
 * syntax, so placing it in minichart.js would make that file unloadable as a
 * plain <script>. The build swaps the module footer instead — see the marker at
 * the bottom of minichart.js.
 *
 * `build:check` lets CI fail a change whose dist/ no longer matches its source.
 * A stale bundle is otherwise invisible until someone loads the CDN copy and
 * gets last month's code.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const terser = require('terser');

const ROOT = path.resolve(__dirname, '..');
const PKG = require(path.join(ROOT, 'package.json'));
const FOOTER_MARKER = '// @module-footer';
const CHECK = process.argv.includes('--check');
// Size is the product's headline differentiator, and it once drifted 8.2 → 10.3
// KB unnoticed because nothing watched it. The build
// fails — in both `build` and `build:check` — if the minified CJS/UMD entry
// exceeds this budget. Raised 10 → 11 KB when push() gained atomic multi-series
// frames (one rebuild per tick), index-aligned placement, an opt-in labels
// contract check, and a ref-counted shared-container overlay: those correctness
// wins earned the headroom, and 11 KB is still tiny.
const SIZE_BUDGET_GZIP_KB = 11;

// Terser keeps `/^!/` comments, so attribution and version survive
// minification. Taken from package.json so it cannot drift from the release.
const banner =
  `/*! MiniChart v${PKG.version} | ${PKG.license} | ${PKG.homepage || 'https://github.com/'} */`;

/** Replace the script/CommonJS footer with a real ESM export. */
function toEsm(src) {
  const at = src.indexOf(FOOTER_MARKER);
  if (at === -1) {
    throw new Error(
      `build: "${FOOTER_MARKER}" not found in minichart.js — the ESM build ` +
      'relies on it to locate the script/CommonJS footer.');
  }
  return src.slice(0, at) +
    '// Generated by build/minify.js — see the module footer in minichart.js.\n' +
    'export default MiniChart;\n' +
    'export { MiniChart };\n';
}

async function minify(code, outName, srcName) {
  const result = await terser.minify({ [srcName]: code }, {
    module: outName.endsWith('.mjs'),
    format: { comments: /^!/, preamble: banner },
    // Property mangling is gated on a leading underscore — the convention every
    // internal field already follows — so the ~100 this._ names collapse to
    // one-letter keys for ~6% off the bundle. The regex cannot reach the
    // Canvas/DOM API (no underscore properties there) and there are no
    // getters/setters to mangle unsafely.
    //
    // No reserved list, deliberately: nothing public starts with an underscore
    // any more, so the prefix means exactly one thing — private, manglable. A
    // reserved list is a second place to remember, and forgetting an entry
    // renames a documented property silently in the minified build only.
    // Anything public must therefore be named without the underscore.
    //
    // pure_getters is safe for the same reason (no getters, all reads
    // side-effect-free) and trims a little more.
    mangle: { properties: { regex: /^_/ } },
    compress: { pure_getters: true },
  });
  if (result.error) throw result.error;
  return result;
}

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
const gzip = (s) => zlib.gzipSync(s).length;

(async () => {
  const src = fs.readFileSync(path.join(ROOT, 'minichart.js'), 'utf8');
  const esmSrc = banner + '\n' + toEsm(src);

  const min = await minify(src, 'minichart.min.js', 'minichart.js');

  // Enforce the size budget on the freshly built code, before anything is
  // written or compared, so both `build` and `build:check` gate on it.
  const minJsGzip = gzip(min.code);
  if (minJsGzip > SIZE_BUDGET_GZIP_KB * 1024) {
    console.error(
      `build: minichart.min.js is ${(minJsGzip / 1024).toFixed(2)} KB gzip, ` +
      `over the ${SIZE_BUDGET_GZIP_KB} KB budget. Trim the code or raise SIZE_BUDGET_GZIP_KB.`);
    process.exit(1);
  }

  // The one authoritative record of the shipped sizes — what the docs and any
  // tooling should read, so a claim can't drift from what was actually built.
  const sizeJson = JSON.stringify({
    version: PKG.version,
    minJs: { raw: min.code.length, gzip: minJsGzip },
  }, null, 2) + '\n';

  const files = {
    'minichart.min.js': min.code,
    'minichart.mjs': esmSrc,
    'size.json': sizeJson,
  };

  const outDir = path.join(ROOT, 'dist');

  if (CHECK) {
    const stale = Object.keys(files).filter((name) => {
      const p = path.join(outDir, name);
      return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== files[name];
    });
    if (stale.length) {
      console.error('dist/ is out of date with minichart.js:');
      for (const name of stale) console.error('  ' + name);
      console.error('\nRun `npm run build` and commit the result.');
      process.exit(1);
    }
    console.log('dist/ matches minichart.js ✓');
    return;
  }

  fs.mkdirSync(outDir, { recursive: true });
  for (const name of Object.keys(files)) {
    fs.writeFileSync(path.join(outDir, name), files[name]);
  }

  const rows = [
    ['dist/minichart.min.js', min.code],
    ['dist/minichart.mjs', esmSrc],
  ];
  const width = Math.max(...rows.map(([n]) => n.length));
  for (const [name, code] of rows) {
    console.log(`${name.padEnd(width)}  ${kb(code.length).padStart(8)}  ` +
                `${kb(gzip(code)).padStart(8)} gzip`);
  }
})().catch((e) => { console.error(e.message || e); process.exit(1); });
